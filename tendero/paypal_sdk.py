"""PayPal Orders v2 / Payments v2 through the official PayPal Server SDK.

The PayPal Server SDK (``paypal-server-sdk``) is generated by **APIMatic** from PayPal's API
definition. This adapter was written with APIMatic's *PayPal Server SDK Context Plugin*
(https://github.com/paypaldev/server-sdk-context-plugin-preview), whose skills ground a coding
agent in the SDK's real surface: flat keyword configuration, controllers as client properties,
the ``options`` dict call shape, the ``ApiResponse`` envelope and the ``requests.Session`` seam.

It exposes the same async interface as :class:`tendero.paypal_client.PayPalClient`, so the
payment lifecycle does not care which one is plugged in (``PAYPAL_SDK=apimatic|rest``):

* create / get / capture orders and get / refund captures go through the SDK's typed models;
* webhook signature verification stays on the REST client, because the Notifications API is
  not part of the generated SDK.

The SDK is synchronous (``requests``), so each call runs in a worker thread. In ``mock`` mode a
small ``requests`` adapter forwards the SDK's HTTP calls to the in-process PayPal simulator, so
the exact same SDK code path is exercised by the tests and the offline demo.
"""
from __future__ import annotations

import asyncio
import json
from typing import Any
from urllib.parse import urlsplit

import httpx
import requests
from requests.structures import CaseInsensitiveDict

from paypalserversdk.configuration import Environment
from paypalserversdk.exceptions.api_exception import ApiException
from paypalserversdk.http.auth.o_auth_2 import ClientCredentialsAuthCredentials
from paypalserversdk.models.amount_breakdown import AmountBreakdown
from paypalserversdk.models.amount_with_breakdown import AmountWithBreakdown
from paypalserversdk.models.checkout_payment_intent import CheckoutPaymentIntent
from paypalserversdk.models.item_category import ItemCategory
from paypalserversdk.models.item_request import ItemRequest
from paypalserversdk.models.money import Money
from paypalserversdk.models.order_request import OrderRequest
from paypalserversdk.models.payment_source import PaymentSource
from paypalserversdk.models.paypal_wallet import PaypalWallet
from paypalserversdk.models.paypal_wallet_experience_context import PaypalWalletExperienceContext
from paypalserversdk.models.purchase_unit_request import PurchaseUnitRequest
from paypalserversdk.models.refund_request import RefundRequest
from paypalserversdk.paypal_serversdk_client import PaypalServersdkClient

from .paypal_client import PayPalClient, PayPalError

SDK_NAME = "PayPal Server SDK (APIMatic)"


class ASGIBridge(requests.adapters.BaseAdapter):
    """``requests`` transport that hands the SDK's calls to an in-process ASGI app.

    Used only with the local simulator: the SDK still builds every request itself (URL, auth,
    headers, JSON body); this adapter just delivers it to ``app`` under ``prefix`` instead of the
    network, on the event loop that owns the app.
    """

    def __init__(self, app, prefix: str):
        super().__init__()
        self.app, self.prefix = app, prefix.rstrip("/")
        self.loop: asyncio.AbstractEventLoop | None = None

    def send(self, request, stream=False, timeout=None, verify=True, cert=None, proxies=None):
        url = urlsplit(request.url)
        path = self.prefix + url.path + (f"?{url.query}" if url.query else "")
        body = request.body.encode() if isinstance(request.body, str) else request.body

        async def call() -> httpx.Response:
            async with httpx.AsyncClient(transport=httpx.ASGITransport(app=self.app),
                                         base_url="http://internal") as c:
                return await c.request(request.method, path, content=body, headers=dict(request.headers))

        r = asyncio.run_coroutine_threadsafe(call(), self.loop).result(timeout=30)
        resp = requests.Response()
        resp.status_code, resp._content = r.status_code, r.content
        resp.headers = CaseInsensitiveDict(r.headers)
        resp.url, resp.request, resp.encoding = request.url, request, "utf-8"
        return resp

    def close(self):
        pass


class PayPalSDKClient:
    """Drop-in for :class:`PayPalClient`, backed by the APIMatic-generated PayPal Server SDK."""

    sdk_name = SDK_NAME

    def __init__(self, client_id: str, client_secret: str, *, sandbox: bool = True,
                 rest: PayPalClient, bridge: ASGIBridge | None = None, timeout: int = 30):
        session = None
        if bridge is not None:
            session = requests.Session()
            session.mount("https://", bridge)
        self.bridge, self.rest = bridge, rest
        self.sdk = PaypalServersdkClient(
            environment=Environment.SANDBOX if sandbox else Environment.PRODUCTION,
            client_credentials_auth_credentials=ClientCredentialsAuthCredentials(
                o_auth_client_id=client_id, o_auth_client_secret=client_secret),
            http_client_instance=session,
            timeout=timeout,
            max_retries=0,  # the sweep is our retry strategy; keeps idempotency keys honest
        )

    async def aclose(self) -> None:
        await self.rest.aclose()

    async def _run(self, op: str, fn, options: dict) -> dict:
        if self.bridge is not None:
            self.bridge.loop = asyncio.get_running_loop()
        try:
            res = await asyncio.to_thread(fn, options)
        except ApiException as e:
            raise PayPalError(e.response_code, _body(e.response.text), op) from e
        # Keep PayPal's wire JSON (links, seller_receivable_breakdown...) exactly as received.
        return _body(res.text)

    # ----------------------------------------------------------------- orders
    async def create_order(self, *, reference_id: str, cart: dict, brand_name: str,
                           return_url: str, cancel_url: str) -> dict:
        cur = cart["currency"]
        body = OrderRequest(
            intent=CheckoutPaymentIntent.CAPTURE,
            purchase_units=[PurchaseUnitRequest(
                reference_id=reference_id, custom_id=reference_id, invoice_id=reference_id,
                description=f"{brand_name} order {reference_id}",
                amount=AmountWithBreakdown(
                    currency_code=cur, value=cart["total"],
                    breakdown=AmountBreakdown(item_total=Money(cur, cart["subtotal"]),
                                              shipping=Money(cur, cart["shipping"]))),
                items=[ItemRequest(name=line["name"][:127], sku=line["sku"], quantity=str(line["quantity"]),
                                   unit_amount=Money(cur, line["unit_price"]),
                                   category=ItemCategory.PHYSICAL_GOODS) for line in cart["lines"]],
            )],
            payment_source=PaymentSource(paypal=PaypalWallet(experience_context=PaypalWalletExperienceContext(
                brand_name=brand_name[:127], user_action="PAY_NOW", shipping_preference="GET_FROM_FILE",
                return_url=return_url, cancel_url=cancel_url))),
        )
        return await self._run("create_order", self.sdk.orders.create_order,
                               {"body": body, "paypal_request_id": f"create-{reference_id}",
                                "prefer": "return=representation"})

    async def get_order(self, order_id: str) -> dict:
        return await self._run("get_order", self.sdk.orders.get_order, {"id": order_id})

    async def capture_order(self, order_id: str) -> dict:
        return await self._run("capture_order", self.sdk.orders.capture_order,
                               {"id": order_id, "paypal_request_id": f"capture-{order_id}",
                                "prefer": "return=representation"})

    # --------------------------------------------------------------- payments
    async def get_capture(self, capture_id: str) -> dict:
        return await self._run("get_capture", self.sdk.payments.get_captured_payment,
                               {"capture_id": capture_id})

    async def refund_capture(self, capture_id: str, *, amount: str | None, currency: str,
                             note: str, request_id: str) -> dict:
        body = RefundRequest(note_to_payer=note[:255], amount=Money(currency, amount)) if amount \
            else RefundRequest(note_to_payer=note[:255])
        return await self._run("refund_capture", self.sdk.payments.refund_captured_payment,
                               {"capture_id": capture_id, "body": body, "paypal_request_id": request_id,
                                "prefer": "return=representation"})

    # --------------------------------------------------------------- webhooks
    async def verify_webhook_signature(self, headers: dict[str, str], event: dict, webhook_id: str) -> bool:
        return await self.rest.verify_webhook_signature(headers, event, webhook_id)


def _body(text: str | None) -> Any:
    try:
        return json.loads(text) if text else {}
    except ValueError:
        return {"raw": (text or "")[:500]}
